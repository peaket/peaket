test('D-T30 ⑤ 워크로드마다 MSK 전용 역할과 고정 세션 이름이 짝을 이룬다', () => {
  const generated = readGenYaml('msk-iam.yaml');
  const byName = new Map(generated.workloads.map((w) => [w.name, w]));

  for (const service of SERVICES) {
    assert.ok(byName.has(`${service}-svc-outbox-relay`), `${service}-svc-outbox-relay가 없다`);
    assert.equal(byName.get(`${service}-svc-outbox-relay`).sessionName, `${service}-svc-outbox-relay-<env>`);
    assert.ok(byName.get(`${service}-svc-outbox-relay`).writeTopics.length > 0, `${service} 릴레이에 쓰기 권한이 없다`);
  }

  // 요청 처리 파드에는 Outbox 쓰기 권한을 주지 않는다(docs/data.md:3164).
  assert.deepEqual(byName.get('purchase-svc').writeTopics, []);
  assert.deepEqual(byName.get('core-svc').writeTopics, []);
  assert.deepEqual(byName.get('ops-svc').writeTopics, []);
  assert.equal(byName.get('purchase-svc').sessionName, 'purchase-svc-<env>');
  assert.equal(byName.get('core-svc').sessionName, 'core-svc-<env>');
  assert.equal(byName.get('ops-svc').sessionName, 'ops-svc-<env>');
  // queue-svc는 Outbox 없이 support.cases-requested 한 토픽에 직접 쓰고, 텔레메트리 클러스터에도 쓴다(docs/infra.md:551).
  const queueWrites = byName.get('queue-svc').writeTopics;
  assert.ok(queueWrites.includes('support.cases-requested'), 'queue-svc가 support.cases-requested에 쓰지 않는다');
  for (const topic of queueWrites) {
    assert.ok(topic === 'support.cases-requested' || topic.startsWith('telemetry.'), `queue-svc API가 예상 밖 토픽에 쓴다: ${topic}`);
  }
  // trust-svc API 파드는 텔레메트리 토픽만 쓴다. 거래·제어 토픽 쓰기는 없다.
  assert.ok(byName.get('trust-svc').writeTopics.length > 0);
  for (const topic of byName.get('trust-svc').writeTopics) {
    assert.match(topic, /^telemetry\./, `trust-svc API가 텔레메트리 밖 토픽에 쓴다: ${topic}`);
  }
  assert.equal(byName.get('schema-registry').sessionName, 'schema-registry-<env>');
  assert.ok(byName.get('schema-registry').readTopics.includes('_schemas'));
  assert.ok(byName.get('schema-registry').writeTopics.includes('_schemas'));
});

