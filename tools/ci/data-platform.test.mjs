/** 생성 pgbouncer.ini의 필수 줄과 DB 여섯을 확인한다(RV093-06). */
function assertPgBouncerIni(ini) {
  assert.match(ini, /^\[databases\]$/m, '[databases]가 없다');
  for (const db of ['purchase', 'payment', 'ticket', 'ops', 'identity', 'core']) {
    assert.match(ini, new RegExp(`^peaket_${db} = `, 'm'), `${db} DB 줄이 없다`);
  }
  for (const line of [
    'pool_mode = transaction',
    'max_prepared_statements = 200',
    'query_wait_timeout = 5',
    'idle_transaction_timeout = 15',
    'query_timeout = 65',
    'server_idle_timeout = 600',
    'server_lifetime = 3600',
    'auth_type = scram-sha-256',
    'auth_file = /etc/pgbouncer/userlist.txt',
    'client_tls_sslmode = require',
    'server_tls_sslmode = verify-full',
  ]) {
    assert.match(ini, new RegExp(`^${line.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'm'), `${line}이 없다`);
  }
  assert.doesNotMatch(ini, /^auth_query/m, 'auth_query를 쓴다');
}

