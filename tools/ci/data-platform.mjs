  add(errors, investigation?.cleanupPolicy === 'delete', 'investigation.requests cleanupPolicy는 delete여야 한다');
  const schemas = topics.get('_schemas');
  add(errors, schemas?.cluster === 'trade-control', '_schemas는 거래·제어 클러스터여야 한다');
  add(errors, schemas?.partitions === 3, '_schemas 파티션은 3개여야 한다');
  add(errors, schemas?.replicationFactor === 3, '_schemas RF는 3이어야 한다');
