function runCli() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      root: { type: 'string' },
      spec: { type: 'string' },
    },
  });
  const command = positionals[0];
  if (!['check', 'write', 'render'].includes(command)) {
    console.error('쓰는 법: node tools/ci/data-platform.mjs <check|write|render> [--root <폴더>] [--spec <경로>]');
    process.exit(2);
  }
  const root = values.root ? resolve(values.root) : DEFAULT_ROOT;
  const specPath = values.spec ? resolve(values.spec) : join(root, SPEC_PATH);
  if (!existsSync(specPath)) {
    console.error(`데이터 계층 기준을 읽지 못했다: ${specPath}`);
    process.exit(2);
  }
  const spec = parse(readFileSync(specPath, 'utf8'));
  const errors = validateData(spec);
  if (errors.length > 0) {
    for (const error of errors) console.error(`막음: ${specPath}: ${error}`);
    process.exit(1);
  }
  const rendered = renderAll(spec);
  const generatedDir = join(root, GENERATED_DIR);
  if (command === 'render') {
    for (const [name, text] of Object.entries(rendered)) {
      console.log(`### ${name}`);
      console.log(text);
    }
    process.exit(0);
  }
  if (command === 'write') {
    mkdirSync(generatedDir, { recursive: true });
    for (const [name, text] of Object.entries(rendered)) writeFileSync(join(generatedDir, name), text, 'utf8');
    console.log(`데이터 계층 생성 파일 ${Object.keys(rendered).length}개를 썼다: ${generatedDir}`);
    process.exit(0);
  }
  let failed = 0;
  for (const [name, text] of Object.entries(rendered)) {
    const path = join(generatedDir, name);
    if (!existsSync(path)) {
      console.error(`막음: ${path}: 생성 파일이 없다`);
      failed += 1;
      continue;
    }
    if (readFileSync(path, 'utf8') !== text) {
      console.error(`막음: ${path}: 생성 파일이 원천과 다르다`);
      failed += 1;
    }
  }
  if (failed > 0) process.exit(1);
  console.log('데이터 계층 기준·생성 파일이 원천과 같다');
  process.exit(0);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  runCli();
}
