export function renderRoleDefaultsSql(spec) {
  const appRoles = new Map();
  for (const role of spec.roles.appHotpath.roles) appRoles.set(role, spec.roles.appHotpath);
  for (const role of spec.roles.appGeneral.roles) appRoles.set(role, spec.roles.appGeneral);
  const lines = [
    header('--').trimEnd(),
    '-- 적용 차례: F-09-2 역할 생성·GRANT 뒤',
    '',
  ];
  for (const service of SERVICES) {
    const appRole = `${service}_app`;
    const app = appRoles.get(appRole);
    if (!app) throw new Error(`역할 기본값에 ${appRole}이 없다`);
    for (const role of [appRole, `${appRole}_clone`]) {
      lines.push(`ALTER ROLE ${role} SET statement_timeout = '${seconds(app.statementTimeoutMs)}';`);
      lines.push(`ALTER ROLE ${role} SET idle_in_transaction_session_timeout = '${seconds(app.idleInTransactionSessionTimeoutMs)}';`);
    }
    lines.push(`ALTER ROLE ${service}_ddl SET statement_timeout = '${seconds(spec.roles.ddl.statementTimeoutMs)}';`);
    lines.push(`ALTER ROLE ${service}_ddl SET idle_in_transaction_session_timeout = '${seconds(spec.roles.ddl.idleInTransactionSessionTimeoutMs)}';`);
    lines.push(`ALTER ROLE ${service}_maintenance SET statement_timeout = '${seconds(spec.roles.maintenance.statementTimeoutMs)}';`);
    lines.push(`ALTER ROLE ${service}_maintenance SET idle_in_transaction_session_timeout = '${seconds(spec.roles.maintenance.idleInTransactionSessionTimeoutMs)}';`);
    lines.push(`ALTER ROLE ${service}_maintenance SET work_mem = '${spec.roles.maintenance.workMem}';`);
    lines.push(`ALTER ROLE ${service}_outbox_relay SET statement_timeout = '${seconds(spec.roles.outboxRelay.statementTimeoutMs)}';`);
    lines.push(`ALTER ROLE ${service}_outbox_relay SET idle_in_transaction_session_timeout = '${seconds(spec.roles.outboxRelay.idleInTransactionSessionTimeoutMs)}';`);
  }
  lines.push('');
  return lines.join('\n');
}

