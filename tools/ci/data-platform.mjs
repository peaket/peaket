function validateMskIam(spec, errors) {
  const iam = spec.mskIam ?? {};
  add(errors, iam.failClosed === true, 'MSK IAM은 역할을 못 맡으면 실패해야 한다');
  add(errors, iam.sessionNamePattern === '<workload>-<env>', 'MSK IAM 세션 이름 패턴이 틀리다');
  const workloads = iam.workloads ?? [];
  add(errors, workloads.length >= 16, 'MSK IAM 워크로드가 16개보다 적다');
  const names = workloads.map((w) => w.name);
  add(errors, new Set(names).size === names.length, 'MSK IAM 워크로드 이름이 겹친다');
  for (const expected of REQUIRED_WORKLOADS) {
    add(errors, names.includes(expected), `MSK IAM ${expected} 워크로드가 없다`);
  }
  for (const workload of workloads) {
    add(errors, Array.isArray(workload.podIdentityRole?.kafkaActions) && workload.podIdentityRole.kafkaActions.length === 0, `${workload.name}의 Pod Identity 역할에 kafka 권한이 있다`);
    add(errors, typeof workload.podIdentityRole?.name === 'string' && workload.podIdentityRole.name.startsWith('peaket-'), `${workload.name}의 Pod Identity 역할 이름이 틀리다`);
    add(errors, typeof workload.mskRole?.name === 'string' && workload.mskRole.name.startsWith('peaket-msk-'), `${workload.name}의 MSK 전용 역할 이름이 틀리다`);
    add(errors, workload.mskRole?.name !== workload.podIdentityRole?.name, `${workload.name}의 MSK 역할과 Pod Identity 역할이 같다`);
    add(errors, workload.mskRole?.trust?.action === 'sts:AssumeRole', `${workload.name}의 MSK 역할 신뢰 동작이 틀리다`);
    add(errors, workload.mskRole?.trust?.principal === workload.podIdentityRole?.name, `${workload.name}의 MSK 역할 신뢰 정책이 다른 주체를 믿는다`);
    add(errors, workload.sessionName === `${workload.name}-<env>`, `${workload.name}의 세션 이름이 패턴과 다르다`);
    const permissions = workload.mskRole?.permissions ?? [];
    add(errors, permissions.length > 0, `${workload.name}의 MSK 권한이 비었다`);
    for (const permission of permissions) {
      add(errors, Array.isArray(permission.actions) && permission.actions.length > 0, `${workload.name}의 MSK 권한 동작이 비었다`);
      add(errors, Array.isArray(permission.resources) && permission.resources.length > 0, `${workload.name}의 MSK 권한 자원이 비었다`);
      for (const action of permission.actions ?? []) {
        add(errors, !action.includes('*'), `${workload.name}의 MSK 권한에 와일드카드가 있다: ${action}`);
        add(errors, ALLOWED_ACTIONS.has(action), `${workload.name}의 MSK 권한이 허용 목록 밖이다: ${action}`);
      }
      for (const resource of permission.resources ?? []) {
        add(errors, !resource.includes('*'), `${workload.name}의 MSK 자원에 와일드카드가 있다: ${resource}`);
        add(errors, /^(topic|group|cluster):[A-Za-z0-9._<>:-]+$/.test(resource), `${workload.name}의 MSK 자원 모양이 틀리다: ${resource}`);
      }
    }
  }
  const byName = new Map(workloads.map((w) => [w.name, w]));
  for (const name of ['purchase-svc', 'core-svc', 'ops-svc']) {
    add(errors, Array.isArray(byName.get(name)?.writeTopics) && byName.get(name).writeTopics.length === 0, `${name} API 파드에 쓰기 권한이 있다`);
  }
  const queueWrites = byName.get('queue-svc')?.writeTopics ?? [];
  add(errors, queueWrites.includes('support.cases-requested'), 'queue-svc가 support.cases-requested에 쓰지 않는다');
  for (const topic of queueWrites) {
    add(errors, topic === 'support.cases-requested' || topic.startsWith('telemetry.'), `queue-svc API가 예상 밖 토픽에 쓴다: ${topic}`);
  }
  const trustWrites = byName.get('trust-svc')?.writeTopics ?? [];
  add(errors, trustWrites.length > 0, 'trust-svc API 파드의 텔레메트리 쓰기가 없다');
  for (const topic of trustWrites) {
    add(errors, topic.startsWith('telemetry.'), `trust-svc API가 텔레메트리 밖 토픽에 쓴다: ${topic}`);
  }
  const registry = byName.get('schema-registry');
  add(errors, registry?.sessionName === 'schema-registry-<env>', 'schema-registry 세션 이름이 틀리다');
  add(errors, registry?.readTopics?.includes('_schemas') === true, 'schema-registry가 _schemas를 읽지 않는다');
  add(errors, registry?.writeTopics?.includes('_schemas') === true, 'schema-registry가 _schemas에 쓰지 않는다');
}

export function validateData(spec) {
  const errors = [];
  if (!spec || typeof spec !== 'object') return ['데이터 계층 기준이 객체가 아니다'];
  add(errors, spec.version === 1, 'version은 1이어야 한다');
  validateRedis(spec, errors);
  validateAurora(spec, errors);
  validateMsk(spec, errors);
  validateSchemaRegistry(spec, errors);
  validatePgBouncer(spec, errors);
  validateRoles(spec, errors);
  validateMskIam(spec, errors);
  return errors;
}

